import { test, mock } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import express from "express";
import { pool } from "../db";
import { registerContractorPayrollRoutes } from "../routes/contractorPayroll";
import { getPayrollReview, getPayStatementPdf, listPayStatements, mutateContractorPayroll, type PayrollActor } from "./contractorPayroll";

test("1099 payroll: real database workflow, privacy, immutability and audit rollback (all fixtures rolled back)", { timeout: 120000 }, async () => {
  const client = await pool.connect();
  await client.query("BEGIN");
  let depth = 0, failAudit = "";
  const query = async (text: string, params?: any[]) => {
    if (text === "BEGIN") return client.query(`SAVEPOINT payroll_test_${++depth}`);
    if (text === "COMMIT") return client.query(`RELEASE SAVEPOINT payroll_test_${depth--}`);
    if (text === "ROLLBACK") {
      await client.query(`ROLLBACK TO SAVEPOINT payroll_test_${depth}`);
      return client.query(`RELEASE SAVEPOINT payroll_test_${depth--}`);
    }
    if (text.startsWith("INSERT INTO contractor_payroll_audit") && params?.[0] === failAudit) return client.query("SELECT 1/0");
    return client.query(text, params);
  };
  const connectMock = mock.method(pool, "connect", async () => ({ query, release() {} }));
  const queryMock = mock.method(pool, "query", query);
  const suffix = randomUUID().slice(0, 10);
  const admin: PayrollActor = { id: `payroll-audit-admin-${suffix}`, role: "admin", firstName: "Payroll", lastName: "Administrator" };
  const a: PayrollActor = { id: `payroll-audit-a-${suffix}`, role: "employee", firstName: "Example", lastName: "Contractor A" };
  const b: PayrollActor = { id: `payroll-audit-b-${suffix}`, role: "employee", firstName: "Example", lastName: "Contractor B" };
  const manager: PayrollActor = { id: `payroll-audit-manager-${suffix}`, role: "manager", firstName: "Example", lastName: "Manager" };
  const change = (action: string, id: number | string, data: unknown) => mutateContractorPayroll(admin, action, String(id), data);
  const expectedSqlFailure = async (sql: string, params: any[], pattern: RegExp) => {
    await client.query("SAVEPOINT expected_failure");
    await assert.rejects(client.query(sql, params), pattern);
    await client.query("ROLLBACK TO SAVEPOINT expected_failure");
    await client.query("RELEASE SAVEPOINT expected_failure");
  };
  let server: ReturnType<ReturnType<typeof express>["listen"]> | undefined;
  try {
    for (const actor of [admin, a, b, manager]) await client.query(`INSERT INTO users(id,role,status,first_name,last_name,is_test_account) VALUES($1,$2,'active',$3,$4,true)`, [actor.id, actor.role, actor.firstName, actor.lastName]);
    const addTime = async (person: string, start: string, end: string | null) => (await client.query(`INSERT INTO time_entries(user_id,clock_in_time,clock_out_time,status) VALUES($1,$2,$3,$4) RETURNING id`, [person, start, end, end ? "clocked_out" : "clocked_in"])).rows[0].id as number;
    const first = await addTime(a.id, "2001-01-02 09:00:00", "2001-01-02 17:00:20");
    const extra = await addTime(a.id, "2001-01-02 18:00:00", "2001-01-02 18:00:20");
    const missing = await addTime(a.id, "2001-01-03 09:00:00", null);
    const zero = await addTime(a.id, "2001-01-04 09:00:00", "2001-01-04 09:00:00");
    const long = await addTime(a.id, "2001-01-05 00:00:00", "2001-01-06 00:00:00");
    await addTime(b.id, "2001-01-02 09:00:00", "2001-01-02 10:00:00");
    const p: any = await change("period", "", { startDate: "2001-01-01", endDate: "2001-01-14", cadence: "biweekly", timezone: "UTC" });
    await assert.rejects(change("period", "", { startDate: "2001-01-14", endDate: "2001-01-20", cadence: "weekly", timezone: "UTC" }), /overlap/i);
    const flagged = (await getPayrollReview(p.id)).contractors.find(person => person.id === a.id)!;
    assert.ok(flagged.flags.includes("Missing clock-out"));
    assert.ok(flagged.flags.includes("Zero or negative shift"));
    assert.ok(flagged.flags.includes("Overlong shift (over 16 hours)"));
    await assert.rejects(change("approve", p.id, { contractorId: a.id }), /flagged/);
    await change("rate", a.id, { rateCents: 2000, reason: "Initial contractor rate" });
    await change("rate", b.id, { rateCents: 1500, reason: "Initial contractor rate" });
    for (const [id, start, end] of [[missing, "2001-01-03T09:00:00Z", "2001-01-03T10:00:00Z"], [zero, "2001-01-04T09:00:00Z", "2001-01-04T10:00:00Z"], [long, "2001-01-05T09:00:00Z", "2001-01-05T17:00:00Z"]] as const) {
      await change("time", id, { clockInTime: start, clockOutTime: end, reason: "Verified original clock records" });
    }
    await change("approve", p.id, { contractorId: a.id });
    await assert.rejects(change("lock", p.id, {}), /Every contractor/);
    await change("time", extra, { clockInTime: "2001-01-02T18:00:00Z", clockOutTime: "2001-01-02T18:00:21Z", reason: "Corrected original seconds" });
    assert.equal((await getPayrollReview(p.id)).contractors.find(person => person.id === a.id)!.approved, false, "Even same-minute changes revoke prior approval");
    await change("approve", p.id, { contractorId: a.id });
    await change("approve", p.id, { contractorId: b.id });
    assert.equal((await getPayrollReview(p.id)).contractors.find(person => person.id === a.id)!.minutes, 1081);
    failAudit = "period_locked";
    await assert.rejects(change("lock", p.id, {}), /division by zero/);
    failAudit = "";
    assert.equal((await getPayrollReview(p.id)).period.status, "draft", "Audit failure rolls lock back");
    await change("lock", p.id, {});
    await assert.rejects(change("time", first, { clockInTime: "2001-01-02T09:00:00Z", clockOutTime: "2001-01-02T17:00:00Z", reason: "Must reject locked edit" }), /locked/);
    await expectedSqlFailure("UPDATE time_entries SET clock_out_time=clock_out_time+interval '1 minute' WHERE id=$1", [first], /locked/);
    await expectedSqlFailure("INSERT INTO time_entries(user_id,clock_in_time,clock_out_time,status) VALUES($1,'2001-01-08 09:00','2001-01-08 10:00','clocked_out')", [a.id], /locked/);
    const s1: any = await change("issue", p.id, { contractorId: a.id, payDate: "2001-01-19" });
    assert.equal(s1.grossCents, 36033);
    assert.equal(s1.ytdGrossCents, 36033);
    const originalPdf = await getPayStatementPdf(a, s1.id);
    assert.ok(originalPdf.bytes.subarray(0, 5).equals(Buffer.from("%PDF-")));
    await assert.rejects(getPayStatementPdf(b, s1.id), /not found/);
    await assert.rejects(change("issue", p.id, { contractorId: a.id, payDate: "2001-01-19" }), /already exists/);
    await change("issue", p.id, { contractorId: b.id, payDate: "2001-01-19" });
    await change("rate", a.id, { rateCents: 2500, reason: "New prospective contract rate" });
    failAudit = "rate_changed";
    await assert.rejects(change("rate", a.id, { rateCents: 3000, reason: "This must roll back" }), /division by zero/);
    failAudit = "";
    assert.equal((await client.query("SELECT rate_cents FROM contractor_payroll_rates WHERE contractor_id=$1", [a.id])).rows[0].rate_cents, 2500);
    assert.equal((await listPayStatements(a, 1, 2001)).statements[0].rateCents, 2000, "Issued rate is immutable");
    const p2: any = await change("period", "", { startDate: "2001-01-15", endDate: "2001-01-28", cadence: "biweekly", timezone: "America/New_York" });
    await addTime(a.id, "2001-01-16 14:00", "2001-01-16 15:00");
    await change("approve", p2.id, { contractorId: a.id });
    await change("lock", p2.id, {});
    const s2: any = await change("issue", p2.id, { contractorId: a.id, payDate: "2001-02-02" });
    assert.equal(s2.grossCents, 2500);
    assert.equal(s2.ytdGrossCents, 38533);
    await change("unlock", p.id, { reason: "Correcting reviewed historical hours" });
    assert.equal((await getPayrollReview(p.id)).contractors.every(person => !person.approved), true);
    await assert.rejects(change("issue", p.id, { contractorId: a.id, payDate: "2001-01-19", replacesStatementId: s1.id, reason: "Must reject unlocked replacement" }), /lock/);
    await change("approve", p.id, { contractorId: a.id });
    await change("approve", p.id, { contractorId: b.id });
    await change("lock", p.id, {});
    failAudit = "statement_reissued";
    await assert.rejects(change("issue", p.id, { contractorId: a.id, payDate: "2001-01-19", replacesStatementId: s1.id, reason: "Injected failure must preserve original" }), /division by zero/);
    failAudit = "";
    assert.equal((await getPayStatementPdf(a, s1.id)).status, "issued", "Failed replacement rolls void and new statement back");
    const replacement: any = await change("issue", p.id, { contractorId: a.id, payDate: "2001-01-19", replacesStatementId: s1.id, reason: "Corrected contracted hourly rate" });
    assert.equal(replacement.grossCents, 45042);
    assert.equal(replacement.ytdGrossCents, 45042);
    assert.equal((await getPayStatementPdf(a, s1.id)).status, "void");
    assert.deepEqual((await getPayStatementPdf(a, s1.id)).bytes, originalPdf.bytes, "Original PDF is retained byte-for-byte");
    assert.equal((await listPayStatements(a, 1, 2001)).ytdGrossCents, 47542, "Annual totals exclude void and include replacement");
    assert.ok((await listPayStatements(a, 1, 2001)).statements.every(statement => statement.contractorId === a.id));
    await expectedSqlFailure("UPDATE contractor_payroll_statements SET gross_cents=1 WHERE id=$1", [replacement.id], /immutable/);
    await expectedSqlFailure("DELETE FROM contractor_payroll_audit WHERE actor_id=$1", [admin.id], /append-only/);
    const p3: any = await change("period", "", { startDate: "2001-02-01", endDate: "2001-02-14", cadence: "biweekly", timezone: "UTC" });
    await addTime(b.id, "2001-02-03 09:00", "2001-02-03 10:00");
    await change("approve", p3.id, { contractorId: b.id });
    await change("lock", p3.id, {});
    failAudit = "statement_generated";
    await assert.rejects(change("issue", p3.id, { contractorId: b.id, payDate: "2001-02-16" }), /division by zero/);
    failAudit = "";
    assert.equal((await client.query("SELECT count(*)::int AS count FROM contractor_payroll_statements WHERE period_id=$1", [p3.id])).rows[0].count, 0);
    for (const actor of [a, manager]) await assert.rejects(mutateContractorPayroll(actor, "rate", actor.id, { rateCents: 1, reason: "Unauthorized change" }), /Only admins/);
    const app = express(); app.use(express.json());
    const actors: Record<string, PayrollActor> = { admin, a, b, manager };
    registerContractorPayrollRoutes(app, (req: any, res, next) => {
      req.user = actors[String(req.headers["x-fixture-actor"])];
      if (!req.user) return void res.status(401).json({ message: "Sign in required" });
      next();
    });
    server = app.listen(0, "127.0.0.1");
    await new Promise<void>(resolve => server!.once("listening", resolve));
    const origin = `http://127.0.0.1:${(server.address() as any).port}/api/contractor-payroll`;
    assert.equal((await fetch(`${origin}/admin`, { headers: { "x-fixture-actor": "a" } })).status, 403);
    assert.equal((await fetch(`${origin}/audit`, { headers: { "x-fixture-actor": "manager" } })).status, 403);
    assert.equal((await fetch(`${origin}/statements/${s1.id}/pdf`, { headers: { "x-fixture-actor": "b" } })).status, 404);
    assert.equal((await fetch(`${origin}/statements/${s1.id}/pdf`, { headers: { "x-fixture-actor": "a" } })).status, 200);
    assert.equal((await fetch(`${origin}?contractorId=${b.id}&year=2001`, { headers: { "x-fixture-actor": "a" } })).status, 400);
    assert.equal((await fetch(origin)).status, 401);
    await mkdir("generated-artifacts/payroll-verification", { recursive: true });
    await writeFile("generated-artifacts/payroll-verification/example-pay-statement.pdf", (await getPayStatementPdf(a, replacement.id)).bytes);
    const audit = await client.query("SELECT action,details FROM contractor_payroll_audit WHERE actor_id=$1 ORDER BY id", [admin.id]);
    for (const action of ["rate_changed", "hours_approved", "period_approved", "period_locked", "period_unlocked", "statement_generated", "statement_voided", "statement_reissued", "time_corrected"]) assert.ok(audit.rows.some(row => row.action === action), action);
    console.log("Verified: daily rounding, all flags, corrections, stale approval invalidation, lock enforcement, retained PDF, old rate snapshot, YTD, void/reissue, own-only routes and four audit-failure rollbacks.");
  } finally {
    if (server) await new Promise<void>(resolve => server!.close(() => resolve()));
    connectMock.mock.restore(); queryMock.mock.restore();
    await client.query("ROLLBACK");
    client.release();
    await pool.end();
  }
});
